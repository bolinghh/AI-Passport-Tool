"""Generate the small, crisp 20 px Passport heading font from the licensed OTF.

Requires Pillow 12.3.0. Body/dynamic city text keeps the existing CJK 16 font.
Threshold 96 preserves crisp strokes; no synthetic emboldening.
No download or modification of the full Chinese font is needed.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[3]
PRODUCT = ROOT / 'products/codex-controller'
SYMBOLS = '应用番茄钟麦克风设置专注时间休息蓝牙安全配对计完成重置取消绑定年月日周一二三四五六晴多云雾雷雨雪像素伙伴迷你钓鱼类图鉴'
points = sorted(set(range(32, 127)) | set(map(ord, SYMBOLS)))
coverage = set(json.loads((PRODUCT / 'font-codepoints.json').read_text()))
assert set(points) <= coverage
source = ROOT / 'assets/fonts/NotoSansSC-Regular.otf'
font = ImageFont.truetype(str(source), 20)
bitmap, descriptors = [], ['    {0},']
for code in points:
    char = chr(code)
    left, top, right, bottom = font.getbbox(char, anchor='ls')
    width, height = right - left, bottom - top
    image = Image.new('L', (max(1, width), max(1, height)))
    ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor='ls')
    bits = [int(value >= 96) for value in image.get_flattened_data()][:width * height]
    offset = len(bitmap)
    for at in range(0, len(bits), 8):
        byte = 0
        for bit in bits[at:at+8]:
            byte = (byte << 1) | bit
        bitmap.append(byte << max(0, 8 - len(bits[at:at+8])))
    descriptors.append('    {.bitmap_index=%d, .adv_w=%d, .box_w=%d, .box_h=%d, .ofs_x=%d, .ofs_y=%d},' %
                       (offset, round(font.getlength(char) * 16), width, height, left, -bottom))
lines = ['/* Generated by tools/generate_ui_font.py; Noto Sans SC, SIL OFL 1.1. */', '#include "lvgl.h"',
         'static const uint8_t bitmap[] = {']
lines += ['    ' + ','.join('0x%02x' % n for n in bitmap[i:i+20]) + ',' for i in range(0, len(bitmap), 20)]
lines += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', *descriptors, '};',
          'static const uint16_t unicode[] = {', '    ' + ','.join(str(n-32) for n in points), '};',
          'static const lv_font_fmt_txt_cmap_t cmaps[] = {{',
          '    .range_start=32, .range_length=%d, .glyph_id_start=1,' % (points[-1]-31),
          '    .unicode_list=unicode, .list_length=%d, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY' % len(points),
          '}};', 'static const lv_font_fmt_txt_dsc_t descriptor = {',
          '    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps, .cmap_num=1, .bpp=1', '};',
          'const lv_font_t passport_ui_20 = {',
          '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
          '    .line_height=24, .base_line=5, .dsc=&descriptor', '};', '']
out = ROOT / 'assets/fonts/passport_ui_20.c'
out.write_text('\n'.join(lines))
manifest = dict(source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                generated_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),
                generator='generate_ui_font.py / Pillow 12.3.0; threshold 96, 1 bpp',
                size=20, codepoints=points)
(PRODUCT / 'ui-font-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'Generated {len(points)} heading glyphs, {len(bitmap)} bitmap bytes')
